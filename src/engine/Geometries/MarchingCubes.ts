// MarchingCubes — 等值面提取 (iso-surface extraction)。
//
// 适配 three.js `examples/jsm/objects/MarchingCubes.js` 并重构为几何体生成器。
// 经典 Marching Cubes 算法 (Lorensen & Cline 1987):
//   1. 把 3D 标量场 (density field) 划分为均匀网格;
//   2. 遍历每个单元格 (cube, 8 个角点),根据角点值与等值面阈值的关系
//      确定该 cube 的构型 (0..255);
//   3. 查表确定该构型产生的三角形 (哪些边上需要插值顶点);
//   4. 在边上用线性插值计算顶点位置,输出三角形。
//
// 用途:
//   - Metaball 渲染 (流体状融合球体)
//   - 体素地形等值面提取
//   - 医学影像 (CT/MRI) 等值面重建
//   - 程序化网格生成 (噪声场 → mesh)
//
// 不变量:
//   - 输出为非索引三角形列表 (每三角形 3 独立顶点);
//   - 法线通过密度场梯度计算 (中心差分),方向指向密度减小方向;
//   - 原始数据不被修改;
//   - 空网格 (无三角形) 返回空 BufferGeometry。
//
// 参考:
//   - Lorensen & Cline "Marching Cubes: A High Resolution 3D Surface
//     Construction Algorithm" (SIGGRAPH 1987)
//   - three.js examples/jsm/objects/MarchingCubes.js
//   - Paul Bourke "Polygonising a Scalar Field"

