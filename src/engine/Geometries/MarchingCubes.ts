/** Metaball 描述 (球心 + 半径平方)。 */
export interface Metaball {
  /** 球心坐标 (网格空间)。 */
  center: Vector3;
  /** 半径平方 (影响强度)。 */
  radiusSq: number;
}

/** Marching Cubes 选项。 */
export interface MarchingCubesOptions {
  /** 网格分辨率 (每轴 cell 数)。默认 32。 */
  resolution?: number;
  /** 等值面阈值。角点值 > isoLevel 视为"内部"。默认 0.5。 */
  isoLevel?: number;
  /** 网格空间尺寸 (每轴长度)。默认 1.0。 */
  size?: number;
  /** 网格空间中心偏移。默认 (0,0,0)。 */
  offset?: Vector3;
  /** 是否计算法线。默认 true。 */
  computeNormals?: boolean;
}

