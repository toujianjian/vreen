/**
 * Marching Cubes 等值面提取器。
 *
 * 用法 1 — 从密度函数生成:
 * ```ts
 * const mc = new MarchingCubes({
 *   resolution: 32,
 *   isoLevel: 0.5,
 *   size: 2,
 *   offset: new Vector3(-1, -1, -1),
 * });
 * const geometry = mc.fromDensity((x, y, z) => {
 *   // 球体密度: 球内 > 0.5, 球外 < 0.5
 *   const r = Math.sqrt(x*x + y*y + z*z);
 *   return 1 - r;
 * });
 * ```
 *
 * 用法 2 — 从 metaball 列表生成:
 * ```ts
 * const geometry = MarchingCubes.fromMetaballs(
 *   [{ center: new Vector3(0, 0, 0), radiusSq: 0.5 }],
 *   { resolution: 32, size: 2, offset: new Vector3(-1, -1, -1) },
 * );
 * ```
 */
export class MarchingCubes {
  readonly resolution: number;
  readonly isoLevel: number;
  readonly size: number;
  readonly offset: Vector3;
  readonly computeNormals: boolean;

  constructor(opts: MarchingCubesOptions = {}) {
    this.resolution = Math.max(2, Math.min(256, Math.floor(opts.resolution ?? 32)));
    this.isoLevel = opts.isoLevel ?? 0.5;
    this.size = opts.size ?? 1.0;
    this.offset = opts.offset ?? new Vector3(0, 0, 0);
    this.computeNormals = opts.computeNormals ?? true;
  }

  /**
   * 从密度函数提取等值面。
   * @param density (x, y, z) => number,返回标量密度值。
   *   值 > isoLevel 的区域为"内部"。
   * @returns BufferGeometry (非索引三角形 + 法线)
   */
  fromDensity(density: (x: number, y: number, z: number) => number): BufferGeometry {
    const { resolution, size, offset } = this;
    // 网格间距
    const step = size / resolution;
    // 采样密度场到 3D 数组 (resolution+1)^3
    const N = resolution + 1;
    const field = new Float32Array(N * N * N);

    for (let zi = 0; zi < N; zi++) {
      const z = offset.z + zi * step;
      for (let yi = 0; yi < N; yi++) {
        const y = offset.y + yi * step;
        for (let xi = 0; xi < N; xi++) {
          const x = offset.x + xi * step;
          field[zi * N * N + yi * N + xi] = density(x, y, z);
        }
      }
    }

    return this._march(field, N, step);
  }

  /**
   * 从 metaball 列表提取等值面。
   * 每个 metaball 贡献 density += radiusSq / (distSq + radiusSq)。
   */
  static fromMetaballs(
    balls: Metaball[],
    opts: MarchingCubesOptions = {},
  ): BufferGeometry {
    const mc = new MarchingCubes(opts);
    return mc.fromDensity((x, y, z) => {
      let d = 0;
      for (const ball of balls) {
        const dx = x - ball.center.x;
        const dy = y - ball.center.y;
        const dz = z - ball.center.z;
        const distSq = dx * dx + dy * dy + dz * dz;
        d += ball.radiusSq / (distSq + ball.radiusSq);
      }
      return d;
    });
  }

  /**
   * 从原始标量场数组提取等值面。
   * @param field 标量场,大小为 N^3 (N = resolution+1),按 z-y-x 排序。
   * @param N 每轴采样数 (= resolution + 1)。
   */
  fromField(field: Float32Array, N: number): BufferGeometry {
    const step = this.size / (N - 1);
    return this._march(field, N, step);
  }

  // ── 内部:Marching Cubes 主循环 ──────────────────────────────

  private _march(field: Float32Array, N: number, step: number): BufferGeometry {
    const { isoLevel, offset } = this;
    const positions: number[] = [];
    const normals: number[] = [];

    // 预计算法线用的梯度 (中心差分)
    // 法线 = -∇density,指向密度减小方向 (向外)
    const computeNormal = this.computeNormals;

    for (let zi = 0; zi < N - 1; zi++) {
      for (let yi = 0; yi < N - 1; yi++) {
        for (let xi = 0; xi < N - 1; xi++) {
          // 8 角点值
          const idx000 = zi * N * N + yi * N + xi;
          const idx001 = zi * N * N + yi * N + (xi + 1);
          const idx010 = zi * N * N + (yi + 1) * N + xi;
          const idx011 = zi * N * N + (yi + 1) * N + (xi + 1);
          const idx100 = (zi + 1) * N * N + yi * N + xi;
          const idx101 = (zi + 1) * N * N + yi * N + (xi + 1);
          const idx110 = (zi + 1) * N * N + (yi + 1) * N + xi;
          const idx111 = (zi + 1) * N * N + (yi + 1) * N + (xi + 1);

          const v0 = field[idx000]; // corner 0: (x, y, z)
          const v1 = field[idx001]; // corner 1: (x+1, y, z)
          const v2 = field[idx011]; // corner 2: (x+1, y+1, z)
          const v3 = field[idx010]; // corner 3: (x, y+1, z)
          const v4 = field[idx100]; // corner 4: (x, y, z+1)
          const v5 = field[idx101]; // corner 5: (x+1, y, z+1)
          const v6 = field[idx111]; // corner 6: (x+1, y+1, z+1)
          const v7 = field[idx110]; // corner 7: (x, y+1, z+1)

          // 计算 cubeindex
          let cubeIndex = 0;
          if (v0 < isoLevel) cubeIndex |= 1;
          if (v1 < isoLevel) cubeIndex |= 2;
          if (v2 < isoLevel) cubeIndex |= 4;
          if (v3 < isoLevel) cubeIndex |= 8;
          if (v4 < isoLevel) cubeIndex |= 16;
          if (v5 < isoLevel) cubeIndex |= 32;
          if (v6 < isoLevel) cubeIndex |= 64;
          if (v7 < isoLevel) cubeIndex |= 128;

          // 完全在内或完全在外 → 无三角形
          if (EDGE_TABLE[cubeIndex] === 0) continue;

          // 角点世界坐标
          const x0 = offset.x + xi * step;
          const y0 = offset.y + yi * step;
          const z0 = offset.z + zi * step;
          const x1 = x0 + step;
          const y1 = y0 + step;
          const z1 = z0 + step;

          const cornerPositions: ReadonlyArray<readonly [number, number, number]> = [
            [x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0],
            [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1],
          ];
          const cornerValues = [v0, v1, v2, v3, v4, v5, v6, v7];

          // 在 12 条边上插值顶点
          const edgeVerts: (number[] | null)[] = new Array(12).fill(null);
          const edgeBits = EDGE_TABLE[cubeIndex];

          for (let e = 0; e < 12; e++) {
            if (!(edgeBits & (1 << e))) continue;
            const [ca, cb] = EDGE_CONNECTIONS[e];
            const va = cornerValues[ca];
            const vb = cornerValues[cb];
            const [pax, pay, paz] = cornerPositions[ca];
            const [pbx, pby, pbz] = cornerPositions[cb];

            // 线性插值: t = (isoLevel - va) / (vb - va)
            const denom = vb - va;
            const t = Math.abs(denom) < 1e-10 ? 0.5 : (isoLevel - va) / denom;

            edgeVerts[e] = [
              pax + t * (pbx - pax),
              pay + t * (pby - pay),
              paz + t * (pbz - paz),
            ];
          }

          // 生成三角形
          const tris = TRI_TABLE[cubeIndex];
          for (let i = 0; i < 16; i += 3) {
            if (tris[i] < 0) break;
            const ev0 = edgeVerts[tris[i]];
            const ev1 = edgeVerts[tris[i + 1]];
            const ev2 = edgeVerts[tris[i + 2]];
            // 防御:跳过未计算的边 (表不一致时)
            if (!ev0 || !ev1 || !ev2) continue;
            positions.push(ev0[0], ev0[1], ev0[2]);
            positions.push(ev1[0], ev1[1], ev1[2]);
            positions.push(ev2[0], ev2[1], ev2[2]);

            if (computeNormal) {
              // 面法线 (叉积)
              const ax = ev1[0] - ev0[0], ay = ev1[1] - ev0[1], az = ev1[2] - ev0[2];
              const bx = ev2[0] - ev0[0], by = ev2[1] - ev0[1], bz = ev2[2] - ev0[2];
              const nx = ay * bz - az * by;
              const ny = az * bx - ax * bz;
              const nz = ax * by - ay * bx;
              const len = Math.hypot(nx, ny, nz) || 1;
              for (let j = 0; j < 3; j++) {
                normals.push(nx / len, ny / len, nz / len);
              }
            }
          }
        }
      }
    }

    const geometry = new BufferGeometry();
    geometry.setAttribute('position', new BufferAttribute(new Float32Array(positions), 3));
    if (computeNormal && normals.length > 0) {
      geometry.setAttribute('normal', new BufferAttribute(new Float32Array(normals), 3));
    }
    geometry.computeBoundingBox();
    geometry.computeBoundingSphere();
    return geometry;
  }
}
